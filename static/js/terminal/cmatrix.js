(function (window, document) {
    "use strict";

    const MODULE_NAME = "cmatrix-client";
    const VERSION = "2.1.0";
    const DEFAULT_ENDPOINT = "/api/terminal/cmatrix";
    const DEFAULT_RECORDING = "/static/data/cmatrix/cmatrix-recording.json";
    const DEFAULT_CONNECT_TIMEOUT = 4000;
    const DEFAULT_RECONNECT_DELAY = 1000;
    const DEFAULT_MAX_RECONNECT_DELAY = 30000;
    const DEFAULT_HEARTBEAT = 15000;
    const DEFAULT_HEARTBEAT_TIMEOUT = 45000;

    function now() { return Date.now(); }
    function iso(value = now()) { return new Date(value).toISOString(); }
    function clampNumber(value, fallback, minimum, maximum) {
        const parsed = Number(value);
        return Number.isFinite(parsed)
            ? Math.min(maximum, Math.max(minimum, parsed))
            : fallback;
    }
    function dispatch(target, type, detail = {}) {
        try {
            target.dispatchEvent(new CustomEvent(type, {
                detail: { type, timestamp: iso(), ...detail }
            }));
        } catch (_error) {
            /* Observers must not break transport. */
        }
    }
    function websocketURL(value) {
        const url = new URL(value || DEFAULT_ENDPOINT, document.baseURI);
        if (url.protocol === "http:") url.protocol = "ws:";
        if (url.protocol === "https:") url.protocol = "wss:";
        if (!["ws:", "wss:"].includes(url.protocol)) {
            throw new TypeError(`cmatrix endpoint must use ws or wss: ${url.href}`);
        }
        return url.href;
    }
    function decodeBase64(value) {
        const binary = window.atob(String(value || ""));
        const bytes = new Uint8Array(binary.length);
        for (let index = 0; index < binary.length; index += 1) {
            bytes[index] = binary.charCodeAt(index);
        }
        return new TextDecoder("utf-8", { fatal: false }).decode(bytes);
    }

    class CmatrixClient extends EventTarget {
        constructor(options = {}) {
            super();
            this.options = {
                endpoint: options.endpoint || options.socketURL || DEFAULT_ENDPOINT,
                recordingURL: options.recordingURL || DEFAULT_RECORDING,
                args: Array.isArray(options.args) ? [...options.args] : [],
                columns: clampNumber(options.columns, 120, 20, 1000),
                rows: clampNumber(options.rows, 40, 10, 500),
                preferRecording: options.preferRecording === true,
                fallbackToRecording: options.fallbackToRecording !== false,
                autoReconnect: options.autoReconnect !== false,
                reconnectDelay: clampNumber(options.reconnectDelay, DEFAULT_RECONNECT_DELAY, 100, 60000),
                maxReconnectDelay: clampNumber(options.maxReconnectDelay, DEFAULT_MAX_RECONNECT_DELAY, 1000, 300000),
                heartbeat: clampNumber(options.heartbeat, DEFAULT_HEARTBEAT, 1000, 120000),
                heartbeatTimeout: clampNumber(options.heartbeatTimeout, DEFAULT_HEARTBEAT_TIMEOUT, 3000, 300000),
                connectTimeout: clampNumber(options.connectTimeout, DEFAULT_CONNECT_TIMEOUT, 500, 120000)
            };
            this.socket = null;
            this.mode = "idle";
            this.state = "idle";
            this.destroyed = false;
            this.manualClose = false;
            this.generation = 0;
            this.reconnectAttempts = 0;
            this.reconnectTimer = 0;
            this.connectTimer = 0;
            this.heartbeatTimer = 0;
            this.replayTimer = 0;
            this.replayFrames = [];
            this.replayIndex = 0;
            this.connectedAt = null;
            this.lastMessageAt = null;
            this.lastPongAt = null;
            this.lastError = null;
            this.recording = null;
            this.decoder = new TextDecoder("utf-8", { fatal: false });
        }

        _setState(state, detail = {}) {
            this.state = state;
            dispatch(this, "state", { state, mode: this.mode, ...detail });
        }

        _socketURL() {
            const url = new URL(websocketURL(this.options.endpoint));
            url.searchParams.set("columns", String(this.options.columns));
            url.searchParams.set("rows", String(this.options.rows));
            if (this.options.args.length) {
                url.searchParams.set("args", JSON.stringify(this.options.args));
            }
            return url.href;
        }

        connect() {
            if (this.destroyed) throw new Error("cmatrix client has been destroyed.");
            if (["connecting", "open"].includes(this.state)) return false;
            this.manualClose = false;
            this._clearReconnect();
            this._clearReplay();
            this.lastError = null;
            const generation = ++this.generation;
            if (this.options.preferRecording) this._startRecording(generation);
            else this._startSocket(generation);
            return true;
        }

        _startSocket(generation) {
            this.mode = "websocket";
            this._setState("connecting");
            let socket;
            try {
                socket = new WebSocket(this._socketURL());
            } catch (error) {
                this.lastError = error instanceof Error ? error : new Error(String(error));
                this._fallbackOrFail(generation);
                return;
            }

            this.socket = socket;
            socket.binaryType = "arraybuffer";
            let opened = false;
            let fallbackStarted = false;

            const fallbackOnce = () => {
                if (fallbackStarted) return;
                fallbackStarted = true;
                this._fallbackOrFail(generation);
            };

            this.connectTimer = window.setTimeout(() => {
                if (generation !== this.generation || opened) return;
                try { socket.close(4000, "connect timeout"); } catch (_error) { /* noop */ }
                fallbackOnce();
            }, this.options.connectTimeout);

            socket.addEventListener("open", () => {
                if (generation !== this.generation || socket !== this.socket) return;
                opened = true;
                this._clearConnectTimer();
                this.connectedAt = iso();
                this.lastMessageAt = this.connectedAt;
                this.lastPongAt = this.connectedAt;
                this.reconnectAttempts = 0;
                this._setState("open", { url: socket.url });
                dispatch(this, "open", { url: socket.url, mode: this.mode });
                this.send({ type: "start", program: "cmatrix", args: this.options.args });
                this.resize(this.options.columns, this.options.rows);
                this._startHeartbeat();
            });

            socket.addEventListener("message", async event => {
                if (generation !== this.generation || socket !== this.socket) return;
                this.lastMessageAt = iso();
                await this._handleSocketMessage(event.data);
            });

            socket.addEventListener("error", () => {
                if (generation !== this.generation || opened) return;
                this.lastError = new Error("cmatrix WebSocket connection failed.");
            });

            socket.addEventListener("close", event => {
                if (generation !== this.generation || socket !== this.socket) return;
                this._clearConnectTimer();
                this._stopHeartbeat();
                this.socket = null;

                if (!opened && !this.manualClose) {
                    fallbackOnce();
                    return;
                }

                this.mode = "idle";
                this._setState("closed", {
                    code: event.code,
                    reason: event.reason,
                    clean: event.wasClean
                });
                dispatch(this, "close", {
                    code: event.code,
                    reason: event.reason,
                    clean: event.wasClean
                });

                if (!this.manualClose && this.options.autoReconnect) {
                    this._scheduleReconnect();
                }
            });
        }

        async _handleSocketMessage(data) {
            if (data instanceof ArrayBuffer) {
                const text = this.decoder.decode(new Uint8Array(data), { stream: true });
                if (text) dispatch(this, "data", { data: text, binary: true, mode: this.mode });
                return;
            }
            if (typeof Blob !== "undefined" && data instanceof Blob) {
                const bytes = new Uint8Array(await data.arrayBuffer());
                const text = this.decoder.decode(bytes, { stream: true });
                if (text) dispatch(this, "data", { data: text, binary: true, mode: this.mode });
                return;
            }

            const text = String(data);
            let message;
            try {
                message = JSON.parse(text);
            } catch (_error) {
                dispatch(this, "data", { data: text, binary: false, mode: this.mode });
                return;
            }

            switch (message.type) {
                case "data":
                    dispatch(this, "data", { data: String(message.data || ""), mode: this.mode });
                    break;
                case "ready":
                    dispatch(this, "ready", message);
                    break;
                case "started":
                    dispatch(this, "started", message);
                    break;
                case "exit":
                    dispatch(this, "exit", message);
                    break;
                case "pong":
                    this.lastPongAt = iso();
                    dispatch(this, "pong", message);
                    break;
                case "status":
                    dispatch(this, "status", message);
                    break;
                case "error":
                    dispatch(this, "error", { error: String(message.message || "cmatrix server error") });
                    break;
                default:
                    dispatch(this, "message", { message });
            }
        }

        _fallbackOrFail(generation) {
            if (generation !== this.generation || this.manualClose || this.destroyed) return;
            this._clearConnectTimer();
            this._stopHeartbeat();

            const socket = this.socket;
            this.socket = null;
            if (socket) {
                try { socket.close(); } catch (_error) { /* noop */ }
            }

            if (this.options.fallbackToRecording) {
                this._startRecording(generation);
                return;
            }

            const message = this.lastError?.message || "cmatrix runtime unavailable.";
            this.mode = "idle";
            this._setState("error", { error: message });
            dispatch(this, "error", { error: message });
            if (this.options.autoReconnect) this._scheduleReconnect();
        }

        async _startRecording(generation) {
            this.mode = "recording";
            this._setState("connecting", { source: this.options.recordingURL });

            try {
                const response = await fetch(
                    new URL(this.options.recordingURL, document.baseURI),
                    { cache: "no-store", credentials: "same-origin" }
                );
                if (!response.ok) {
                    throw new Error(`cmatrix recording request failed: HTTP ${response.status}`);
                }

                const recording = await response.json();
                if (generation !== this.generation || this.manualClose || this.destroyed) return;
                if (!Array.isArray(recording.frames) || !recording.frames.length) {
                    throw new Error("cmatrix recording contains no frames.");
                }

                this.recording = recording;
                this.replayFrames = recording.frames;
                this.replayIndex = 0;
                this.connectedAt = iso();
                this.lastMessageAt = this.connectedAt;
                this.lastError = null;
                this._setState("open", { source: this.options.recordingURL });
                dispatch(this, "open", { url: this.options.recordingURL, mode: this.mode });
                dispatch(this, "ready", {
                    type: "ready",
                    program: "cmatrix",
                    mode: this.mode,
                    columns: recording.columns || this.options.columns,
                    rows: recording.rows || this.options.rows,
                    upstreamCommit: recording.upstream_commit || null
                });
                dispatch(this, "started", { type: "started", program: "cmatrix", mode: this.mode });
                this._replayNext(generation);
            } catch (error) {
                if (generation !== this.generation) return;
                this.lastError = error instanceof Error ? error : new Error(String(error));
                this.mode = "idle";
                this._setState("error", { error: this.lastError.message });
                dispatch(this, "error", { error: this.lastError.message });
                if (this.options.autoReconnect) this._scheduleReconnect();
            }
        }

        _replayNext(generation) {
            if (
                generation !== this.generation ||
                this.manualClose ||
                this.destroyed ||
                this.mode !== "recording" ||
                !this.replayFrames.length
            ) return;

            const frame = this.replayFrames[this.replayIndex];
            let text = "";
            try {
                text = decodeBase64(frame.data);
            } catch (_error) {
                text = "";
            }

            if (text) {
                this.lastMessageAt = iso();
                dispatch(this, "data", { data: text, binary: true, mode: this.mode });
            }

            this.replayIndex += 1;
            if (this.replayIndex >= this.replayFrames.length) {
                this.replayIndex = 0;
                dispatch(this, "loop", { mode: this.mode });
            }

            const delay = clampNumber(frame.delay_ms, 33, 5, 2000);
            this.replayTimer = window.setTimeout(
                () => this._replayNext(generation),
                delay
            );
        }

        send(payload) {
            if (this.mode === "recording") return true;
            if (!this.socket || this.socket.readyState !== WebSocket.OPEN) return false;
            this.socket.send(typeof payload === "string" ? payload : JSON.stringify(payload));
            return true;
        }

        resize(columns, rows) {
            this.options.columns = clampNumber(columns, this.options.columns, 20, 1000);
            this.options.rows = clampNumber(rows, this.options.rows, 10, 500);
            return this.mode === "recording" || this.send({
                type: "resize",
                columns: this.options.columns,
                rows: this.options.rows
            });
        }

        input(data) {
            return this.mode === "recording"
                ? false
                : this.send({ type: "input", data: String(data) });
        }

        signal(name = "SIGTERM") {
            return this.mode === "recording"
                ? false
                : this.send({ type: "signal", signal: name });
        }

        restart() {
            this.disconnect(1000, "restart");
            this.manualClose = false;
            return this.connect();
        }

        configure(options = {}) {
            if (options.endpoint !== undefined || options.socketURL !== undefined) {
                this.options.endpoint = options.endpoint || options.socketURL;
            }
            if (options.recordingURL !== undefined) this.options.recordingURL = options.recordingURL;
            if (options.args !== undefined) this.options.args = Array.isArray(options.args) ? [...options.args] : [];
            if (options.preferRecording !== undefined) this.options.preferRecording = options.preferRecording === true;
            if (options.fallbackToRecording !== undefined) this.options.fallbackToRecording = options.fallbackToRecording !== false;
            if (options.autoReconnect !== undefined) this.options.autoReconnect = options.autoReconnect !== false;
            if (options.columns !== undefined || options.rows !== undefined) {
                this.resize(options.columns, options.rows);
            }
            return this.status();
        }

        disconnect(code = 1000, reason = "closed") {
            this.manualClose = true;
            this.generation += 1;
            this._clearConnectTimer();
            this._clearReconnect();
            this._stopHeartbeat();
            this._clearReplay();

            const socket = this.socket;
            this.socket = null;
            if (socket) {
                try {
                    if (socket.readyState === WebSocket.OPEN) {
                        socket.send(JSON.stringify({ type: "signal", signal: "SIGTERM" }));
                    }
                    socket.close(code, reason);
                } catch (_error) {
                    /* noop */
                }
            }

            const previousMode = this.mode;
            this.mode = "idle";
            this._setState("closed", { code, reason, manual: true, previousMode });
            dispatch(this, "close", { code, reason, clean: true, previousMode });
        }

        _scheduleReconnect() {
            if (this.destroyed || this.manualClose || !this.options.autoReconnect) return;
            this._clearReconnect();
            this.reconnectAttempts += 1;
            const delay = Math.min(
                this.options.maxReconnectDelay,
                this.options.reconnectDelay * Math.pow(2, this.reconnectAttempts - 1)
            );
            this.reconnectTimer = window.setTimeout(() => this.connect(), delay);
            this._setState("reconnecting", { attempt: this.reconnectAttempts, delay });
            dispatch(this, "reconnect", { attempt: this.reconnectAttempts, delay });
        }

        _startHeartbeat() {
            this._stopHeartbeat();
            this.heartbeatTimer = window.setInterval(() => {
                const lastPong = this.lastPongAt ? Date.parse(this.lastPongAt) : 0;
                if (lastPong && now() - lastPong > this.options.heartbeatTimeout) {
                    try {
                        this.socket?.close(4001, "heartbeat timeout");
                    } catch (_error) {
                        /* noop */
                    }
                    return;
                }
                this.send({ type: "ping", timestamp: now() });
            }, this.options.heartbeat);
        }

        _stopHeartbeat() {
            if (this.heartbeatTimer) window.clearInterval(this.heartbeatTimer);
            this.heartbeatTimer = 0;
        }

        _clearConnectTimer() {
            if (this.connectTimer) window.clearTimeout(this.connectTimer);
            this.connectTimer = 0;
        }

        _clearReconnect() {
            if (this.reconnectTimer) window.clearTimeout(this.reconnectTimer);
            this.reconnectTimer = 0;
        }

        _clearReplay() {
            if (this.replayTimer) window.clearTimeout(this.replayTimer);
            this.replayTimer = 0;
            this.replayFrames = [];
            this.replayIndex = 0;
        }

        status() {
            return {
                name: MODULE_NAME,
                version: VERSION,
                state: this.state,
                mode: this.mode,
                connected: this.state === "open",
                connecting: this.state === "connecting",
                endpoint: this.options.endpoint,
                recordingURL: this.options.recordingURL,
                args: [...this.options.args],
                dimensions: {
                    columns: this.options.columns,
                    rows: this.options.rows
                },
                connectedAt: this.connectedAt,
                lastMessageAt: this.lastMessageAt,
                lastPongAt: this.lastPongAt,
                reconnectAttempts: this.reconnectAttempts,
                recordingFrames: this.recording?.frames?.length || 0,
                upstreamCommit: this.recording?.upstream_commit || null,
                lastError: this.lastError?.message || null,
                destroyed: this.destroyed
            };
        }

        destroy() {
            if (this.destroyed) return false;
            this.disconnect(1000, "destroyed");
            this.destroyed = true;
            dispatch(this, "destroy", {});
            return true;
        }
    }

    const api = Object.freeze({
        name: MODULE_NAME,
        version: VERSION,
        CmatrixClient,
        websocketURL,
        create(options) {
            return new CmatrixClient(options);
        }
    });

    window.SpeciedexTerminalCmatrixClient = api;
    window.SpeciedexTerminalModules = window.SpeciedexTerminalModules || {};
    window.SpeciedexTerminalModules[MODULE_NAME] = api;

    document.dispatchEvent(new CustomEvent(
        "speciedex:terminal-module-available",
        { detail: { name: MODULE_NAME, module: api } }
    ));
})(window, document);
