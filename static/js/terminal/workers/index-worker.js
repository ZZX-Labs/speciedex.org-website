"use strict";

const WORKER_NAME = "index";
const WORKER_VERSION = "3.0.0";

const DEFAULT_LIMIT = 50;
const MAX_LIMIT = 10000;
const MAX_DOCUMENTS = 1000000;
const MAX_FIELDS = 512;
const DEFAULT_PROGRESS_INTERVAL = 5000;
const MIN_PROGRESS_INTERVAL = 100;
const MAX_PROGRESS_INTERVAL = 100000;
const YIELD_INTERVAL = 2048;

const state = {
    documents: [],
    fields: [],
    idField: "id",
    exactIndexes: new Map(),
    prefixIndexes: new Map(),
    tokenIndex: new Map(),
    documentTokens: [],
    documentFieldValues: [],
    idToIndex: new Map(),
    version: 0,
    builtAt: null,
    buildDurationMs: 0
};

const activeRequests = new Map();
const cancelledRequests = new Set();

function now() {
    return (
        typeof performance !== "undefined" &&
        typeof performance.now === "function"
    )
        ? performance.now()
        : Date.now();
}

function normalizeText(value) {
    return String(value ?? "").trim();
}

function normalizeKey(value) {
    return normalizeText(value).toLowerCase();
}

function normalizeField(value) {
    return normalizeText(value)
        .replace(/-/g, "_");
}

function normalizeBoolean(value, fallback = false) {
    if (typeof value === "boolean") {
        return value;
    }

    if (typeof value === "number") {
        return value !== 0;
    }

    const text = normalizeKey(value);

    if (["true", "1", "yes", "on"].includes(text)) {
        return true;
    }

    if (["false", "0", "no", "off", ""].includes(text)) {
        return false;
    }

    return fallback;
}

function asArray(value) {
    if (value === undefined || value === null) {
        return [];
    }

    return Array.isArray(value)
        ? value
        : [value];
}

function uniqueStrings(value) {
    return [
        ...new Set(
            asArray(value)
                .flatMap(item =>
                    typeof item === "string"
                        ? item.split(",")
                        : [item]
                )
                .map(normalizeField)
                .filter(Boolean)
        )
    ];
}

function clampInteger(value, fallback, minimum, maximum) {
    const parsed = Number.parseInt(value, 10);

    if (!Number.isFinite(parsed)) {
        return fallback;
    }

    return Math.min(
        maximum,
        Math.max(minimum, parsed)
    );
}

function createError(message, code, name = "Error") {
    const error = new Error(message);
    error.name = name;
    error.code = code;
    return error;
}

function serializeError(error) {
    return {
        name: error?.name || "Error",
        message: error?.message || String(error),
        stack: error?.stack || null,
        code: error?.code || null
    };
}

function post(type, id, payload = {}) {
    self.postMessage({
        type,
        id,
        worker: WORKER_NAME,
        workerVersion: WORKER_VERSION,
        ...payload
    });
}

function respond(id, result, error = null) {
    post(
        "response",
        id,
        error
            ? { error: serializeError(error) }
            : { result }
    );
}

function postProgress(id, phase, completed, total, extra = {}) {
    const percent = total > 0
        ? Math.min(100, (completed / total) * 100)
        : 100;

    post("progress", id, {
        phase,
        completed,
        total,
        percent,
        ...extra
    });
}

function yieldToWorker() {
    return new Promise(resolve => {
        setTimeout(resolve, 0);
    });
}

function assertActive(id) {
    if (id === null || id === undefined) {
        return;
    }

    if (
        cancelledRequests.has(id) ||
        activeRequests.get(id)?.cancelled === true
    ) {
        throw createError(
            "Index worker request cancelled.",
            "INDEX_WORKER_CANCELLED",
            "AbortError"
        );
    }
}

function markCancelled(targetId) {
    if (targetId === null || targetId === undefined) {
        return false;
    }

    cancelledRequests.add(targetId);

    const request = activeRequests.get(targetId);

    if (request) {
        request.cancelled = true;
        return true;
    }

    return false;
}

function normalizeMessage(raw) {
    const message =
        raw && typeof raw === "object"
            ? raw
            : {};

    const payload =
        message.payload ??
        message.data ??
        message.options ??
        {};

    return {
        id:
            message.id ??
            message.requestId ??
            message.request_id ??
            null,

        type:
            normalizeKey(
                message.type ??
                message.operation ??
                message.action ??
                message.command
            ),

        payload:
            payload &&
            typeof payload === "object"
                ? payload
                : {},

        targetId:
            message.targetId ??
            message.target_id ??
            payload?.targetId ??
            payload?.target_id ??
            payload?.id ??
            null
    };
}

self.addEventListener("message", async event => {
    const message = normalizeMessage(event.data);

    if (message.type === "cancel" || message.type === "abort") {
        const found = markCancelled(message.targetId);

        if (
            message.id !== null &&
            message.id !== message.targetId
        ) {
            respond(message.id, {
                cancelled: true,
                found,
                targetId: message.targetId
            });
        }

        return;
    }

    const id =
        message.id ??
        `${WORKER_NAME}:${Date.now()}:${Math.random()
            .toString(36)
            .slice(2)}`;

    activeRequests.set(id, {
        cancelled: false,
        startedAt: now(),
        type: message.type
    });

    cancelledRequests.delete(id);

    try {
        const result = await handle(
            message.type,
            message.payload,
            id
        );

        assertActive(id);
        respond(id, result);
    } catch (error) {
        respond(id, null, error);
    } finally {
        activeRequests.delete(id);
        cancelledRequests.delete(id);
    }
});

async function handle(type, payload, id) {
    switch (type) {
        case "build":
        case "rebuild":
        case "index":
            return buildIndex(payload, id);

        case "search":
        case "query":
            return searchIndex(payload, id);

        case "get":
        case "find":
            return getDocument(payload);

        case "add":
        case "append":
            return addDocuments(payload, id);

        case "update":
        case "upsert":
            return updateDocuments(payload, id);

        case "remove":
        case "delete":
            return removeDocuments(payload, id);

        case "fields":
            return {
                fields: [...state.fields],
                idField: state.idField
            };

        case "facets":
        case "facet":
            return {
                facets: buildFacets(
                    state.documents,
                    payload.fields ??
                    payload.facets,
                    payload.limit ??
                    payload.facetLimit ??
                    payload.facet_limit
                )
            };

        case "clear":
        case "reset":
            clearIndex();

            return {
                cleared: true,
                version: state.version
            };

        case "status":
            return status();

        case "ping":
            return {
                pong: true,
                worker: WORKER_NAME,
                version: WORKER_VERSION,
                timestamp: new Date().toISOString()
            };

        default:
            throw createError(
                `Unsupported index operation: ${type || "(empty)"}`,
                "INDEX_WORKER_UNSUPPORTED_OPERATION"
            );
    }
}

function status() {
    return {
        ready: true,
        worker: WORKER_NAME,
        workerVersion: WORKER_VERSION,
        documents: state.documents.length,
        fields: [...state.fields],
        exactIndexes: state.exactIndexes.size,
        prefixIndexes: state.prefixIndexes.size,
        tokens: state.tokenIndex.size,
        idField: state.idField,
        version: state.version,
        builtAt: state.builtAt,
        buildDurationMs: state.buildDurationMs,
        activeRequests: activeRequests.size,
        limits: {
            defaultLimit: DEFAULT_LIMIT,
            maxLimit: MAX_LIMIT,
            maxDocuments: MAX_DOCUMENTS,
            maxFields: MAX_FIELDS
        }
    };
}

function normalizeDocuments(payload) {
    const candidate =
        payload.records ??
        payload.documents ??
        payload.items ??
        payload.results ??
        payload.rows ??
        payload.data ??
        [];

    if (Array.isArray(candidate)) {
        return candidate;
    }

    if (
        candidate &&
        typeof candidate === "object"
    ) {
        for (const key of [
            "records",
            "documents",
            "items",
            "results",
            "rows",
            "data"
        ]) {
            if (Array.isArray(candidate[key])) {
                return candidate[key];
            }
        }
    }

    return [];
}

async function buildIndex(payload = {}, id = null) {
    const startedAt = now();
    const documents = normalizeDocuments(payload);

    if (documents.length > MAX_DOCUMENTS) {
        throw createError(
            `Index document limit exceeded: ${documents.length} > ${MAX_DOCUMENTS}.`,
            "INDEX_WORKER_DOCUMENT_LIMIT",
            "RangeError"
        );
    }

    const fields = uniqueStrings(payload.fields).length
        ? uniqueStrings(payload.fields)
        : discoverFields(documents);

    if (fields.length > MAX_FIELDS) {
        throw createError(
            `Index field limit exceeded: ${fields.length} > ${MAX_FIELDS}.`,
            "INDEX_WORKER_FIELD_LIMIT",
            "RangeError"
        );
    }

    state.documents = [...documents];
    state.fields = fields;
    state.idField = normalizeField(
        payload.idField ??
        payload.id_field ??
        payload.key ??
        "id"
    ) || "id";

    resetStructures(documents.length);

    const progressEnabled = normalizeBoolean(
        payload.progress,
        true
    );

    const progressInterval = clampInteger(
        payload.progressInterval ??
        payload.progress_interval,
        DEFAULT_PROGRESS_INTERVAL,
        MIN_PROGRESS_INTERVAL,
        MAX_PROGRESS_INTERVAL
    );

    for (let index = 0; index < documents.length; index += 1) {
        assertActive(id);
        indexDocument(documents[index], index);

        if (
            progressEnabled &&
            index > 0 &&
            index % progressInterval === 0
        ) {
            postProgress(
                id,
                "build",
                index,
                documents.length,
                {
                    tokens: state.tokenIndex.size
                }
            );
        }

        if (index > 0 && index % YIELD_INTERVAL === 0) {
            await yieldToWorker();
        }
    }

    state.version += 1;
    state.builtAt = new Date().toISOString();
    state.buildDurationMs = now() - startedAt;

    if (progressEnabled) {
        postProgress(
            id,
            "complete",
            documents.length,
            documents.length,
            {
                tokens: state.tokenIndex.size
            }
        );
    }

    return status();
}

function resetStructures(documentCount = 0) {
    state.exactIndexes = new Map();
    state.prefixIndexes = new Map();
    state.tokenIndex = new Map();
    state.documentTokens = new Array(documentCount);
    state.documentFieldValues = new Array(documentCount);
    state.idToIndex = new Map();

    for (const field of state.fields) {
        state.exactIndexes.set(field, new Map());
        state.prefixIndexes.set(field, new Map());
    }
}

function clearIndex() {
    state.documents = [];
    state.fields = [];
    state.idField = "id";
    resetStructures(0);
    state.version += 1;
    state.builtAt = null;
    state.buildDurationMs = 0;
}

function discoverFields(documents) {
    const fields = new Set();

    for (const document of documents) {
        collectFieldPaths(document, "", fields);

        if (fields.size >= MAX_FIELDS) {
            break;
        }
    }

    return [...fields]
        .map(normalizeField)
        .filter(Boolean)
        .slice(0, MAX_FIELDS);
}

function collectFieldPaths(value, prefix, output, depth = 0) {
    if (
        value === null ||
        value === undefined ||
        depth > 8
    ) {
        return;
    }

    if (Array.isArray(value)) {
        for (const item of value.slice(0, 16)) {
            collectFieldPaths(item, prefix, output, depth + 1);
        }
        return;
    }

    if (typeof value !== "object") {
        if (prefix) {
            output.add(prefix);
        }
        return;
    }

    for (const [key, child] of Object.entries(value)) {
        const path = prefix
            ? `${prefix}.${key}`
            : key;

        if (
            child === null ||
            child === undefined ||
            typeof child !== "object"
        ) {
            output.add(path);
        } else {
            collectFieldPaths(child, path, output, depth + 1);
        }

        if (output.size >= MAX_FIELDS) {
            return;
        }
    }
}

function indexDocument(document, index) {
    const tokenSet = new Set();
    const cachedFields = new Map();

    const idValue = fieldValues(
        document,
        state.idField
    )[0];

    const idKey = canonicalKey(idValue);

    if (idKey !== null) {
        state.idToIndex.set(idKey, index);
    }

    for (const field of state.fields) {
        const values = fieldValues(document, field);
        cachedFields.set(field, values);

        const exactIndex = state.exactIndexes.get(field);
        const prefixIndex = state.prefixIndexes.get(field);

        for (const value of values) {
            const normalized = normalizeSearchText(value);

            if (!normalized) {
                continue;
            }

            addSetIndex(exactIndex, normalized, index);

            for (const prefix of prefixesFor(normalized)) {
                addSetIndex(prefixIndex, prefix, index);
            }

            for (const token of tokenizeValue(normalized)) {
                tokenSet.add(token);
                addSetIndex(state.tokenIndex, token, index);
            }
        }
    }

    state.documentTokens[index] = tokenSet;
    state.documentFieldValues[index] = cachedFields;
}

function addSetIndex(index, key, documentIndex) {
    let matches = index.get(key);

    if (!matches) {
        matches = new Set();
        index.set(key, matches);
    }

    matches.add(documentIndex);
}

function prefixesFor(value) {
    const prefixes = [];
    const maximum = Math.min(value.length, 64);

    for (let length = 1; length <= maximum; length += 1) {
        prefixes.push(value.slice(0, length));
    }

    return prefixes;
}

async function searchIndex(payload = {}, id = null) {
    const startedAt = now();
    const query = normalizeText(
        payload.query ??
        payload.q ??
        payload.term ??
        payload.text
    );

    const limit = clampInteger(
        payload.limit ??
        payload.perPage ??
        payload.per_page,
        DEFAULT_LIMIT,
        1,
        MAX_LIMIT
    );

    const explicitOffset =
        payload.offset !== undefined &&
        payload.offset !== null;

    const offset = clampInteger(
        payload.offset,
        0,
        0,
        Number.MAX_SAFE_INTEGER
    );

    const page = clampInteger(
        payload.page,
        1,
        1,
        Number.MAX_SAFE_INTEGER
    );

    const effectiveOffset = explicitOffset
        ? offset
        : (page - 1) * limit;

    const fields = uniqueStrings(payload.fields).length
        ? uniqueStrings(payload.fields)
        : state.fields;

    const filters =
        payload.filters ??
        payload.filter ??
        payload.where ??
        {};

    const candidateIndexes = getCandidateIndexes(
        query,
        fields,
        payload
    );

    const matches = [];
    const progressEnabled = normalizeBoolean(
        payload.progress,
        false
    );

    const progressInterval = clampInteger(
        payload.progressInterval ??
        payload.progress_interval,
        DEFAULT_PROGRESS_INTERVAL,
        MIN_PROGRESS_INTERVAL,
        MAX_PROGRESS_INTERVAL
    );

    for (
        let cursor = 0;
        cursor < candidateIndexes.length;
        cursor += 1
    ) {
        assertActive(id);

        const index = candidateIndexes[cursor];
        const document = state.documents[index];

        if (!document) {
            continue;
        }

        if (!matchesFilters(document, filters)) {
            continue;
        }

        const score = scoreDocument(
            document,
            index,
            query,
            fields,
            payload
        );

        if (query && score <= 0) {
            continue;
        }

        matches.push({
            document,
            index,
            score
        });

        if (
            progressEnabled &&
            cursor > 0 &&
            cursor % progressInterval === 0
        ) {
            postProgress(
                id,
                "search",
                cursor,
                candidateIndexes.length,
                {
                    matched: matches.length
                }
            );
        }

        if (cursor > 0 && cursor % YIELD_INTERVAL === 0) {
            await yieldToWorker();
        }
    }

    const sortRules = normalizeSort(
        payload.sort ??
        payload.orderBy ??
        payload.order_by,
        payload.order ??
        payload.direction
    );

    if (sortRules.length) {
        matches.sort((left, right) => {
            for (const rule of sortRules) {
                const compared = compareDocuments(
                    left.document,
                    right.document,
                    rule.field,
                    rule.order
                );

                if (compared !== 0) {
                    return compared;
                }
            }

            return right.score - left.score ||
                left.index - right.index;
        });
    } else {
        matches.sort((left, right) =>
            right.score - left.score ||
            left.index - right.index
        );
    }

    const total = matches.length;
    const requestedAll = normalizeBoolean(
        payload.all ??
        payload.returnAll ??
        payload.return_all,
        false
    );

    const selected = requestedAll
        ? matches
        : matches.slice(
            effectiveOffset,
            effectiveOffset + limit
        );

    const records = selected.map(match =>
        projectDocument(
            match.document,
            payload.select ??
            payload.projection
        )
    );

    const facetsScope = normalizeKey(
        payload.facetsScope ??
        payload.facets_scope ??
        "matches"
    );

    const facetDocuments = facetsScope === "page"
        ? selected.map(match => match.document)
        : matches.map(match => match.document);

    const result = {
        query,
        total,
        matched: total,
        returned: records.length,
        offset: requestedAll ? 0 : effectiveOffset,
        limit: requestedAll ? total : limit,
        page: requestedAll
            ? 1
            : Math.floor(effectiveOffset / limit) + 1,
        pages: requestedAll
            ? (total > 0 ? 1 : 0)
            : Math.ceil(total / limit),
        hasPrevious: !requestedAll && effectiveOffset > 0,
        hasNext:
            !requestedAll &&
            effectiveOffset + selected.length < total,
        records,
        facets: buildFacets(
            facetDocuments,
            payload.facets,
            payload.facetLimit ??
            payload.facet_limit
        ),
        candidates: candidateIndexes.length,
        elapsed_ms: now() - startedAt,
        index_version: state.version,
        workerVersion: WORKER_VERSION
    };

    if (normalizeBoolean(
        payload.includeScores ??
        payload.include_scores,
        false
    )) {
        result.scores = selected.map(match => ({
            index: match.index,
            score: match.score
        }));
    }

    if (normalizeBoolean(
        payload.includeIndexes ??
        payload.include_indexes,
        false
    )) {
        result.indexes = selected.map(match => match.index);
    }

    if (progressEnabled) {
        postProgress(
            id,
            "complete",
            candidateIndexes.length,
            candidateIndexes.length,
            {
                matched: total,
                returned: records.length
            }
        );
    }

    return result;
}

function getCandidateIndexes(query, fields, options = {}) {
    if (!query) {
        return Array.from(
            { length: state.documents.length },
            (_value, index) => index
        );
    }

    const normalizedQuery = normalizeSearchText(query);
    const mode = normalizeKey(
        options.mode ??
        options.match ??
        ""
    );

    if (
        (normalizeBoolean(options.exact, false) || mode === "exact") &&
        fields.length === 1
    ) {
        const matches =
            state.exactIndexes
                .get(fields[0])
                ?.get(normalizedQuery);

        return matches
            ? [...matches]
            : [];
    }

    if (
        (normalizeBoolean(options.prefix, false) || mode === "prefix") &&
        fields.length === 1
    ) {
        const matches =
            state.prefixIndexes
                .get(fields[0])
                ?.get(normalizedQuery);

        return matches
            ? [...matches]
            : [];
    }

    const tokens = tokenizeValue(normalizedQuery);
    const tokenSets = tokens
        .map(token => state.tokenIndex.get(token))
        .filter(Boolean);

    if (!tokenSets.length) {
        return Array.from(
            { length: state.documents.length },
            (_value, index) => index
        );
    }

    const tokenMode = normalizeKey(
        options.tokenMode ??
        options.token_mode ??
        "and"
    );

    if (tokenMode === "or") {
        return [
            ...new Set(
                tokenSets.flatMap(set => [...set])
            )
        ];
    }

    let result = new Set(tokenSets[0]);

    for (let index = 1; index < tokenSets.length; index += 1) {
        result = intersectSets(result, tokenSets[index]);

        if (!result.size) {
            break;
        }
    }

    return [...result];
}

function scoreDocument(
    document,
    index,
    query,
    fields,
    options = {}
) {
    if (!query) {
        return 1;
    }

    const normalizedQuery = normalizeSearchText(query);
    const queryTokens = tokenizeValue(normalizedQuery);
    const fuzzyEnabled = normalizeBoolean(
        options.fuzzy,
        true
    );

    let score = 0;

    for (const field of fields) {
        const weight = fieldWeight(field, options.weights);
        const values =
            state.documentFieldValues[index]?.get(field) ??
            fieldValues(document, field);

        for (const value of values) {
            const candidate = normalizeSearchText(value);

            if (!candidate) {
                continue;
            }

            if (candidate === normalizedQuery) {
                score += 40 * weight;
                continue;
            }

            if (candidate.startsWith(normalizedQuery)) {
                score += 24 * weight;
            }

            if (candidate.includes(normalizedQuery)) {
                score += 12 * weight;
            }

            const candidateTokens = new Set(
                tokenizeValue(candidate)
            );

            for (const token of queryTokens) {
                if (candidateTokens.has(token)) {
                    score += 5 * weight;
                } else if (
                    fuzzyEnabled &&
                    fuzzyTokenMatch(candidateTokens, token)
                ) {
                    score += 2 * weight;
                }
            }
        }
    }

    return score;
}

function fieldWeight(field, weights) {
    if (
        weights &&
        typeof weights === "object" &&
        Number.isFinite(Number(weights[field]))
    ) {
        return Number(weights[field]);
    }

    const normalized = normalizeField(field).toLowerCase();

    if (
        normalized === state.idField ||
        normalized.endsWith("_id") ||
        normalized.includes("speciedex_id")
    ) {
        return 10;
    }

    if (
        [
            "scientific_name",
            "canonical_name",
            "accepted_name"
        ].includes(normalized)
    ) {
        return 9;
    }

    if (
        [
            "common_name",
            "vernacular_name",
            "english_name"
        ].includes(normalized)
    ) {
        return 7;
    }

    if (
        normalized.includes("synonym") ||
        normalized.includes("alias")
    ) {
        return 6;
    }

    if (
        [
            "genus",
            "species",
            "subspecies",
            "family",
            "order",
            "class",
            "phylum",
            "kingdom",
            "domain"
        ].includes(normalized)
    ) {
        return 5;
    }

    if (
        normalized.includes("provider") ||
        normalized.includes("source")
    ) {
        return 2;
    }

    return 1;
}

function fuzzyTokenMatch(candidateTokens, queryToken) {
    if (queryToken.length < 4) {
        return false;
    }

    const threshold =
        queryToken.length <= 6
            ? 1
            : 2;

    for (const candidate of candidateTokens) {
        if (
            Math.abs(candidate.length - queryToken.length) >
            threshold
        ) {
            continue;
        }

        if (
            levenshtein(candidate, queryToken, threshold) <=
            threshold
        ) {
            return true;
        }
    }

    return false;
}

function matchesFilters(document, filters) {
    if (
        !filters ||
        typeof filters !== "object" ||
        Array.isArray(filters)
    ) {
        return true;
    }

    if ("$and" in filters) {
        return asArray(filters.$and).every(group =>
            matchesFilters(document, group)
        );
    }

    if ("$or" in filters) {
        return asArray(filters.$or).some(group =>
            matchesFilters(document, group)
        );
    }

    if ("$not" in filters) {
        return !matchesFilters(document, filters.$not);
    }

    for (const [field, expected] of Object.entries(filters)) {
        if (field.startsWith("$")) {
            continue;
        }

        const values = fieldValues(document, field);

        if (!matchFilterValues(values, expected)) {
            return false;
        }
    }

    return true;
}

function matchFilterValues(values, expected) {
    if (
        expected &&
        typeof expected === "object" &&
        !Array.isArray(expected)
    ) {
        return Object.entries(expected).every(
            ([operator, operand]) =>
                evaluateOperator(values, operator, operand)
        );
    }

    if (Array.isArray(expected)) {
        return expected.some(value =>
            values.some(actual =>
                compareValues(actual, value)
            )
        );
    }

    return values.some(actual =>
        compareValues(actual, expected)
    );
}

function evaluateOperator(values, operator, expected) {
    switch (normalizeKey(operator)) {
        case "$eq":
        case "eq":
            return values.some(value =>
                compareValues(value, expected)
            );

        case "$ne":
        case "ne":
            return values.length === 0 ||
                values.every(value =>
                    !compareValues(value, expected)
                );

        case "$gt":
        case "gt":
            return values.some(value =>
                comparable(value, expected) > 0
            );

        case "$gte":
        case "gte":
            return values.some(value =>
                comparable(value, expected) >= 0
            );

        case "$lt":
        case "lt":
            return values.some(value =>
                comparable(value, expected) < 0
            );

        case "$lte":
        case "lte":
            return values.some(value =>
                comparable(value, expected) <= 0
            );

        case "$contains":
        case "contains":
            return values.some(value =>
                normalizeSearchText(value).includes(
                    normalizeSearchText(expected)
                )
            );

        case "$in":
        case "in":
            return values.some(value =>
                asArray(expected).some(item =>
                    compareValues(value, item)
                )
            );

        case "$nin":
        case "nin":
            return values.every(value =>
                asArray(expected).every(item =>
                    !compareValues(value, item)
                )
            );

        case "$exists":
        case "exists": {
            const exists = values.some(value =>
                value !== null &&
                value !== undefined &&
                value !== ""
            );

            return normalizeBoolean(expected, true)
                ? exists
                : !exists;
        }

        case "$regex":
        case "regex": {
            const regex = regexFrom(expected);

            return values.some(value =>
                regex.test(normalizeText(value))
            );
        }

        default:
            throw createError(
                `Unsupported index filter operator: ${operator}`,
                "INDEX_WORKER_UNSUPPORTED_FILTER_OPERATOR"
            );
    }
}

function normalizeSort(sort, fallbackOrder = "asc") {
    if (!sort) {
        return [];
    }

    if (typeof sort === "string") {
        return sort
            .split(",")
            .map(normalizeText)
            .filter(Boolean)
            .map(token => {
                const descending = token.startsWith("-");
                const ascending = token.startsWith("+");
                const field = descending || ascending
                    ? token.slice(1)
                    : token;

                return {
                    field,
                    order: descending
                        ? "desc"
                        : normalizeOrder(fallbackOrder)
                };
            })
            .filter(rule => rule.field);
    }

    if (Array.isArray(sort)) {
        return sort.flatMap(item =>
            normalizeSort(item, fallbackOrder)
        );
    }

    if (typeof sort === "object") {
        if (sort.field || sort.path || sort.key) {
            return [{
                field: normalizeField(
                    sort.field ??
                    sort.path ??
                    sort.key
                ),
                order: normalizeOrder(
                    sort.order ??
                    sort.direction ??
                    fallbackOrder
                )
            }].filter(rule => rule.field);
        }

        return Object.entries(sort)
            .map(([field, order]) => ({
                field: normalizeField(field),
                order: normalizeOrder(order)
            }))
            .filter(rule => rule.field);
    }

    return [];
}

function normalizeOrder(value) {
    return normalizeKey(value) === "desc" ||
        Number(value) === -1
        ? "desc"
        : "asc";
}

function compareDocuments(left, right, field, order = "asc") {
    const direction = normalizeOrder(order) === "desc"
        ? -1
        : 1;

    const a = fieldValues(left, field)[0];
    const b = fieldValues(right, field)[0];

    if (a === b) {
        return 0;
    }

    if (a === undefined || a === null) {
        return 1;
    }

    if (b === undefined || b === null) {
        return -1;
    }

    return comparable(a, b) * direction;
}

function projectDocument(document, fields) {
    const requested = uniqueStrings(fields);

    if (!requested.length) {
        return document;
    }

    const output = {};

    for (const field of requested) {
        const values = fieldValues(document, field);

        setPath(
            output,
            field,
            values.length <= 1
                ? values[0] ?? null
                : values
        );
    }

    return output;
}

function buildFacets(documents, requested, limit = 100) {
    const fields = uniqueStrings(requested);

    if (!fields.length) {
        return {};
    }

    const facetLimit = clampInteger(
        limit,
        100,
        1,
        1000
    );

    const facets = {};

    for (const field of fields) {
        const counts = new Map();

        for (const document of documents) {
            const seen = new Set();

            for (const value of fieldValues(document, field)) {
                const key = facetKey(value);

                if (!key || seen.has(key)) {
                    continue;
                }

                seen.add(key);
                counts.set(
                    key,
                    (counts.get(key) || 0) + 1
                );
            }
        }

        facets[field] = [...counts.entries()]
            .sort((left, right) =>
                right[1] - left[1] ||
                left[0].localeCompare(
                    right[0],
                    undefined,
                    {
                        numeric: true,
                        sensitivity: "base"
                    }
                )
            )
            .slice(0, facetLimit)
            .map(([value, count]) => ({
                value,
                count
            }));
    }

    return facets;
}

function getDocument(payload = {}) {
    const idField = normalizeField(
        payload.idField ??
        payload.id_field ??
        state.idField
    );

    const idValue =
        payload.id ??
        payload.value ??
        payload.key;

    if (idValue === undefined || idValue === null) {
        throw createError(
            "A document identifier is required.",
            "INDEX_WORKER_ID_REQUIRED",
            "TypeError"
        );
    }

    if (idField === state.idField) {
        const index = state.idToIndex.get(
            canonicalKey(idValue)
        );

        return index === undefined
            ? null
            : state.documents[index] ?? null;
    }

    return state.documents.find(document =>
        fieldValues(document, idField).some(value =>
            compareValues(value, idValue)
        )
    ) || null;
}

async function addDocuments(payload = {}, id = null) {
    const incoming = normalizeDocuments(payload);

    if (
        state.documents.length + incoming.length >
        MAX_DOCUMENTS
    ) {
        throw createError(
            "Index document limit exceeded.",
            "INDEX_WORKER_DOCUMENT_LIMIT",
            "RangeError"
        );
    }

    const start = state.documents.length;
    state.documents.push(...incoming);
    state.documentTokens.length = state.documents.length;
    state.documentFieldValues.length = state.documents.length;

    for (let index = 0; index < incoming.length; index += 1) {
        assertActive(id);
        indexDocument(incoming[index], start + index);

        if (index > 0 && index % YIELD_INTERVAL === 0) {
            await yieldToWorker();
        }
    }

    state.version += 1;
    state.builtAt = new Date().toISOString();

    return {
        added: incoming.length,
        documents: state.documents.length,
        version: state.version
    };
}

async function updateDocuments(payload = {}, id = null) {
    const incoming = normalizeDocuments(payload);
    const idField = normalizeField(
        payload.idField ??
        payload.id_field ??
        state.idField
    );

    const replace = normalizeBoolean(
        payload.replace,
        false
    );

    const addMissing = normalizeBoolean(
        payload.addMissing ??
        payload.add_missing,
        true
    );

    let updated = 0;
    let added = 0;
    let skipped = 0;

    for (let index = 0; index < incoming.length; index += 1) {
        assertActive(id);

        const document = incoming[index];
        const idValue = fieldValues(document, idField)[0];
        const key = canonicalKey(idValue);

        let targetIndex;

        if (idField === state.idField) {
            targetIndex = state.idToIndex.get(key);
        } else {
            targetIndex = state.documents.findIndex(existing =>
                fieldValues(existing, idField).some(value =>
                    compareValues(value, idValue)
                )
            );
        }

        if (
            targetIndex !== undefined &&
            targetIndex !== -1
        ) {
            state.documents[targetIndex] = replace
                ? document
                : {
                    ...state.documents[targetIndex],
                    ...document
                };

            updated += 1;
        } else if (addMissing) {
            state.documents.push(document);
            added += 1;
        } else {
            skipped += 1;
        }

        if (index > 0 && index % YIELD_INTERVAL === 0) {
            await yieldToWorker();
        }
    }

    await rebuildCurrentIndex(id, payload.progress);

    return {
        updated,
        added,
        skipped,
        documents: state.documents.length,
        version: state.version
    };
}

async function removeDocuments(payload = {}, id = null) {
    const idField = normalizeField(
        payload.idField ??
        payload.id_field ??
        state.idField
    );

    const ids = asArray(
        payload.ids ??
        payload.id ??
        payload.value
    ).filter(value =>
        value !== undefined &&
        value !== null
    );

    const keys = new Set(
        ids.map(canonicalKey)
    );

    const retained = [];
    let removed = 0;

    for (
        let index = 0;
        index < state.documents.length;
        index += 1
    ) {
        assertActive(id);

        const document = state.documents[index];
        const values = fieldValues(document, idField);

        const remove = values.some(value =>
            keys.has(canonicalKey(value))
        );

        if (remove) {
            removed += 1;
        } else {
            retained.push(document);
        }

        if (index > 0 && index % YIELD_INTERVAL === 0) {
            await yieldToWorker();
        }
    }

    state.documents = retained;
    await rebuildCurrentIndex(id, payload.progress);

    return {
        removed,
        documents: state.documents.length,
        version: state.version
    };
}

async function rebuildCurrentIndex(id, progress = false) {
    const startedAt = now();
    const documents = state.documents;
    resetStructures(documents.length);

    for (let index = 0; index < documents.length; index += 1) {
        assertActive(id);
        indexDocument(documents[index], index);

        if (
            normalizeBoolean(progress, false) &&
            index > 0 &&
            index % DEFAULT_PROGRESS_INTERVAL === 0
        ) {
            postProgress(
                id,
                "rebuild",
                index,
                documents.length
            );
        }

        if (index > 0 && index % YIELD_INTERVAL === 0) {
            await yieldToWorker();
        }
    }

    state.version += 1;
    state.builtAt = new Date().toISOString();
    state.buildDurationMs = now() - startedAt;
}

function tokenizePath(path) {
    return normalizeField(path)
        .replace(/\[["']?([^"'[\]]+)["']?\]/g, ".$1")
        .split(".")
        .map(normalizeText)
        .filter(Boolean);
}

function fieldValues(document, field) {
    if (
        document === null ||
        document === undefined
    ) {
        return [];
    }

    const parts = tokenizePath(field);

    if (!parts.length) {
        return flatten(document);
    }

    return resolveParts([document], parts, 0);
}

function resolveParts(values, parts, index) {
    if (index >= parts.length) {
        return flatten(values);
    }

    const part = parts[index];
    const next = [];

    for (const value of values) {
        if (value === null || value === undefined) {
            continue;
        }

        if (Array.isArray(value)) {
            for (const item of value) {
                if (part === "*") {
                    next.push(item);
                } else if (
                    item &&
                    typeof item === "object" &&
                    part in item
                ) {
                    next.push(item[part]);
                }
            }

            if (/^\d+$/.test(part)) {
                const indexed = value[Number(part)];

                if (indexed !== undefined) {
                    next.push(indexed);
                }
            }

            continue;
        }

        if (typeof value !== "object") {
            continue;
        }

        if (part === "*") {
            next.push(...Object.values(value));
            continue;
        }

        if (part in value) {
            next.push(value[part]);
            continue;
        }

        const camel = part.replace(
            /_([a-z])/g,
            (_match, character) =>
                character.toUpperCase()
        );

        if (camel in value) {
            next.push(value[camel]);
        }
    }

    return resolveParts(next, parts, index + 1);
}

function flatten(value, output = []) {
    if (Array.isArray(value)) {
        for (const item of value) {
            flatten(item, output);
        }

        return output;
    }

    if (
        value &&
        typeof value === "object" &&
        !(value instanceof Date)
    ) {
        for (const item of Object.values(value)) {
            flatten(item, output);
        }

        return output;
    }

    if (value !== undefined && value !== null) {
        output.push(value);
    }

    return output;
}

function setPath(target, path, value) {
    const parts = tokenizePath(path);

    if (!parts.length) {
        return;
    }

    let cursor = target;

    for (let index = 0; index < parts.length - 1; index += 1) {
        const part = parts[index];

        if (
            !cursor[part] ||
            typeof cursor[part] !== "object" ||
            Array.isArray(cursor[part])
        ) {
            cursor[part] = {};
        }

        cursor = cursor[part];
    }

    cursor[parts[parts.length - 1]] = value;
}

function normalizeSearchText(value) {
    return normalizeText(value)
        .normalize("NFKD")
        .replace(/\p{M}+/gu, "")
        .toLowerCase();
}

function tokenizeValue(value) {
    return [
        ...new Set(
            normalizeSearchText(value)
                .split(/[^\p{L}\p{N}._:-]+/u)
                .filter(Boolean)
        )
    ];
}

function compareValues(left, right) {
    if (left === right) {
        return true;
    }

    if (
        left === null ||
        left === undefined ||
        right === null ||
        right === undefined
    ) {
        return false;
    }

    if (
        normalizeText(left) !== "" &&
        normalizeText(right) !== "" &&
        Number.isFinite(Number(left)) &&
        Number.isFinite(Number(right))
    ) {
        return Number(left) === Number(right);
    }

    return normalizeSearchText(left) ===
        normalizeSearchText(right);
}

function comparable(left, right) {
    if (
        normalizeText(left) !== "" &&
        normalizeText(right) !== "" &&
        Number.isFinite(Number(left)) &&
        Number.isFinite(Number(right))
    ) {
        return Number(left) - Number(right);
    }

    const leftDate = parseDate(left);
    const rightDate = parseDate(right);

    if (
        leftDate !== null &&
        rightDate !== null
    ) {
        return leftDate - rightDate;
    }

    return normalizeText(left).localeCompare(
        normalizeText(right),
        undefined,
        {
            numeric: true,
            sensitivity: "base"
        }
    );
}

function parseDate(value) {
    if (
        value instanceof Date &&
        Number.isFinite(value.getTime())
    ) {
        return value.getTime();
    }

    if (typeof value !== "string") {
        return null;
    }

    const text = value.trim();

    if (
        !/^\d{4}-\d{2}-\d{2}/.test(text) &&
        !/[T:\-\/]/.test(text)
    ) {
        return null;
    }

    const parsed = Date.parse(text);

    return Number.isFinite(parsed)
        ? parsed
        : null;
}

function canonicalKey(value) {
    if (value === null || value === undefined) {
        return null;
    }

    if (typeof value === "object") {
        try {
            return stableStringify(value);
        } catch (_error) {
            return String(value);
        }
    }

    return normalizeSearchText(value);
}

function stableStringify(value) {
    if (
        value === null ||
        typeof value !== "object"
    ) {
        return JSON.stringify(value);
    }

    if (Array.isArray(value)) {
        return `[${value
            .map(stableStringify)
            .join(",")}]`;
    }

    return `{${Object.keys(value)
        .sort()
        .map(key =>
            `${JSON.stringify(key)}:${stableStringify(value[key])}`
        )
        .join(",")}}`;
}

function facetKey(value) {
    if (value === null) {
        return "null";
    }

    if (value === undefined) {
        return "";
    }

    if (typeof value === "object") {
        try {
            return stableStringify(value);
        } catch (_error) {
            return normalizeText(value);
        }
    }

    return normalizeText(value);
}

function regexFrom(value) {
    if (value instanceof RegExp) {
        return new RegExp(
            value.source,
            sanitizeRegexFlags(value.flags)
        );
    }

    if (
        value &&
        typeof value === "object" &&
        value.pattern !== undefined
    ) {
        return new RegExp(
            normalizeText(value.pattern),
            sanitizeRegexFlags(value.flags)
        );
    }

    const text = normalizeText(value);
    const match = text.match(
        /^\/((?:\\.|[^/])+)\/([dgimsuvy]*)$/
    );

    if (match) {
        return new RegExp(
            match[1],
            sanitizeRegexFlags(match[2])
        );
    }

    return new RegExp(text, "i");
}

function sanitizeRegexFlags(flags) {
    return [
        ...new Set(
            normalizeText(flags)
                .replace(/[gy]/g, "")
                .split("")
                .filter(flag =>
                    "dimsuv".includes(flag)
                )
        )
    ].join("");
}

function intersectSets(left, right) {
    const smaller =
        left.size <= right.size
            ? left
            : right;

    const larger =
        smaller === left
            ? right
            : left;

    return new Set(
        [...smaller].filter(value =>
            larger.has(value)
        )
    );
}

function levenshtein(left, right, maximum = Infinity) {
    const a = normalizeSearchText(left);
    const b = normalizeSearchText(right);

    if (a === b) {
        return 0;
    }

    if (!a.length) {
        return b.length;
    }

    if (!b.length) {
        return a.length;
    }

    if (Math.abs(a.length - b.length) > maximum) {
        return maximum + 1;
    }

    const previous = new Uint32Array(a.length + 1);
    const current = new Uint32Array(a.length + 1);

    for (let column = 0; column <= a.length; column += 1) {
        previous[column] = column;
    }

    for (let row = 1; row <= b.length; row += 1) {
        current[0] = row;
        let rowMinimum = current[0];

        for (let column = 1; column <= a.length; column += 1) {
            const substitution =
                previous[column - 1] +
                (
                    b[row - 1] === a[column - 1]
                        ? 0
                        : 1
                );

            current[column] = Math.min(
                substitution,
                current[column - 1] + 1,
                previous[column] + 1
            );

            rowMinimum = Math.min(
                rowMinimum,
                current[column]
            );
        }

        if (rowMinimum > maximum) {
            return maximum + 1;
        }

        previous.set(current);
    }

    return previous[a.length];
}
