"use strict";

const WORKER_NAME = "library";
const WORKER_VERSION = "3.0.0";

const DEFAULT_LIMIT = 100;
const MAX_LIMIT = 10000;
const MAX_COLLECTIONS = 1000;
const MAX_RECORDS_PER_COLLECTION = 1000000;
const DEFAULT_PROGRESS_INTERVAL = 5000;
const MIN_PROGRESS_INTERVAL = 100;
const MAX_PROGRESS_INTERVAL = 100000;
const YIELD_INTERVAL = 2048;
const MAX_SNAPSHOTS_PER_COLLECTION = 25;

const collections = new Map();
const snapshots = new Map();
const activeRequests = new Map();
const cancelledRequests = new Set();

function now() {
    return (
        typeof performance !== "undefined" &&
        typeof performance.now === "function"
    )
        ? performance.now()
        : Date.now();
}

function normalizeText(value) {
    return String(value ?? "").trim();
}

function normalizeKey(value) {
    return normalizeText(value).toLowerCase();
}

function normalizeName(value) {
    const name = normalizeText(value);

    if (!name) {
        throw createError(
            "A library collection name is required.",
            "LIBRARY_WORKER_NAME_REQUIRED",
            "TypeError"
        );
    }

    if (
        name.includes("..") ||
        name.includes("\\") ||
        name.includes("/") ||
        /[\u0000-\u001f\u007f]/.test(name)
    ) {
        throw createError(
            `Invalid library collection name: ${value}`,
            "LIBRARY_WORKER_INVALID_NAME",
            "TypeError"
        );
    }

    return name;
}

function normalizeBoolean(value, fallback = false) {
    if (typeof value === "boolean") {
        return value;
    }

    if (typeof value === "number") {
        return value !== 0;
    }

    const text = normalizeKey(value);

    if (["true", "1", "yes", "on"].includes(text)) {
        return true;
    }

    if (["false", "0", "no", "off", ""].includes(text)) {
        return false;
    }

    return fallback;
}

function asArray(value) {
    if (value === undefined || value === null) {
        return [];
    }

    return Array.isArray(value)
        ? value
        : [value];
}

function uniqueStrings(value) {
    return [
        ...new Set(
            asArray(value)
                .flatMap(item =>
                    typeof item === "string"
                        ? item.split(",")
                        : [item]
                )
                .map(normalizeText)
                .filter(Boolean)
        )
    ];
}

function integer(value, fallback, minimum, maximum) {
    const parsed = Number.parseInt(value, 10);

    if (!Number.isFinite(parsed)) {
        return fallback;
    }

    return Math.min(
        maximum,
        Math.max(minimum, parsed)
    );
}

function createError(message, code, name = "Error") {
    const error = new Error(message);
    error.name = name;
    error.code = code;
    return error;
}

function serializeError(error) {
    return {
        name: error?.name || "Error",
        message: error?.message || String(error),
        stack: error?.stack || null,
        code: error?.code || null
    };
}

function post(type, id, payload = {}) {
    self.postMessage({
        type,
        id,
        worker: WORKER_NAME,
        workerVersion: WORKER_VERSION,
        ...payload
    });
}

function respond(id, result, error = null) {
    post(
        "response",
        id,
        error
            ? { error: serializeError(error) }
            : { result }
    );
}

function postProgress(id, phase, completed, total, extra = {}) {
    const percent = total > 0
        ? Math.min(100, (completed / total) * 100)
        : 100;

    post("progress", id, {
        phase,
        completed,
        total,
        percent,
        ...extra
    });
}

function yieldToWorker() {
    return new Promise(resolve => {
        setTimeout(resolve, 0);
    });
}

function assertActive(id) {
    if (id === null || id === undefined) {
        return;
    }

    if (
        cancelledRequests.has(id) ||
        activeRequests.get(id)?.cancelled === true
    ) {
        throw createError(
            "Library worker request cancelled.",
            "LIBRARY_WORKER_CANCELLED",
            "AbortError"
        );
    }
}

function markCancelled(targetId) {
    if (targetId === null || targetId === undefined) {
        return false;
    }

    cancelledRequests.add(targetId);

    const request = activeRequests.get(targetId);

    if (request) {
        request.cancelled = true;
        return true;
    }

    return false;
}

function normalizeMessage(raw) {
    const message =
        raw && typeof raw === "object"
            ? raw
            : {};

    const payload =
        message.payload ??
        message.data ??
        message.options ??
        {};

    return {
        id:
            message.id ??
            message.requestId ??
            message.request_id ??
            null,

        type:
            normalizeKey(
                message.type ??
                message.operation ??
                message.action ??
                message.command
            ),

        payload:
            payload &&
            typeof payload === "object"
                ? payload
                : {},

        targetId:
            message.targetId ??
            message.target_id ??
            payload?.targetId ??
            payload?.target_id ??
            payload?.id ??
            null
    };
}

self.addEventListener("message", async event => {
    const message = normalizeMessage(event.data);

    if (message.type === "cancel" || message.type === "abort") {
        const found = markCancelled(message.targetId);

        /*
        Only acknowledge a cancellation when the cancel request has its own
        identifier. Reusing the target identifier would resolve the original
        WorkerPool request before its AbortError response is emitted.
        */
        if (
            message.id !== null &&
            message.id !== message.targetId
        ) {
            respond(message.id, {
                cancelled: true,
                found,
                targetId: message.targetId
            });
        }

        return;
    }

    const id =
        message.id ??
        `${WORKER_NAME}:${Date.now()}:${Math.random()
            .toString(36)
            .slice(2)}`;

    activeRequests.set(id, {
        cancelled: false,
        startedAt: now(),
        type: message.type
    });

    cancelledRequests.delete(id);

    try {
        const result = await handle(
            message.type,
            message.payload,
            id
        );

        assertActive(id);
        respond(id, result);
    } catch (error) {
        respond(id, null, error);
    } finally {
        activeRequests.delete(id);
        cancelledRequests.delete(id);
    }
});

async function handle(type, payload, id) {
    switch (type) {
        case "set":
        case "replace":
            return setCollection(payload, id);

        case "get":
        case "query":
        case "select":
            return getCollection(payload, id);

        case "append":
        case "add":
            return appendCollection(payload, id, false);

        case "prepend":
            return appendCollection(payload, id, true);

        case "merge":
        case "upsert":
            return mergeCollection(payload, id);

        case "list":
        case "collections":
            return listCollections(payload);

        case "has":
        case "exists":
            return {
                exists: collections.has(
                    normalizeName(
                        payload.name ??
                        payload.collection
                    )
                )
            };

        case "delete":
        case "remove":
            return deleteCollection(payload);

        case "rename":
            return renameCollection(payload);

        case "clone":
        case "copy":
            return cloneCollection(payload, id);

        case "clear":
        case "reset":
            return clearCollections(payload);

        case "count":
            return {
                count: countCollection(payload)
            };

        case "stats":
            return collectionStats(payload);

        case "dedupe":
        case "deduplicate":
            return deduplicateCollection(payload, id);

        case "facets":
        case "facet":
            return collectionFacets(payload);

        case "export":
            return exportCollection(payload);

        case "import":
            return importCollection(payload, id);

        case "snapshot":
            return snapshotCollection(payload, id);

        case "restore":
            return restoreSnapshot(payload, id);

        case "snapshots":
            return listSnapshots(payload);

        case "batch":
        case "transaction":
            return executeBatch(payload, id);

        case "status":
            return status();

        case "ping":
            return {
                pong: true,
                worker: WORKER_NAME,
                version: WORKER_VERSION,
                timestamp: new Date().toISOString()
            };

        default:
            throw createError(
                `Unsupported library operation: ${type || "(empty)"}`,
                "LIBRARY_WORKER_UNSUPPORTED_OPERATION"
            );
    }
}

function normalizeRecords(payload) {
    const candidate =
        payload.records ??
        payload.documents ??
        payload.items ??
        payload.results ??
        payload.rows ??
        payload.data ??
        [];

    if (Array.isArray(candidate)) {
        return candidate;
    }

    if (
        candidate &&
        typeof candidate === "object"
    ) {
        for (const key of [
            "records",
            "documents",
            "items",
            "results",
            "rows",
            "data"
        ]) {
            if (Array.isArray(candidate[key])) {
                return candidate[key];
            }
        }
    }

    return [];
}

function createCollection(name, records = [], metadata = {}) {
    const timestamp = new Date().toISOString();

    return {
        name,
        records,
        metadata: {
            ...(
                metadata &&
                typeof metadata === "object"
                    ? metadata
                    : {}
            )
        },
        createdAt: timestamp,
        updatedAt: timestamp,
        version: 1
    };
}

function requireCollection(name) {
    const normalized = normalizeName(name);
    const collection = collections.get(normalized);

    if (!collection) {
        throw createError(
            `Unknown library collection: ${normalized}`,
            "LIBRARY_WORKER_COLLECTION_NOT_FOUND"
        );
    }

    return collection;
}

function ensureCollectionCapacity(name, count) {
    if (count > MAX_RECORDS_PER_COLLECTION) {
        throw createError(
            `Collection "${name}" exceeds the maximum record count of ${MAX_RECORDS_PER_COLLECTION}.`,
            "LIBRARY_WORKER_RECORD_LIMIT",
            "RangeError"
        );
    }
}

function ensureCollectionSlot(name) {
    if (
        !collections.has(name) &&
        collections.size >= MAX_COLLECTIONS
    ) {
        throw createError(
            `Maximum collection count of ${MAX_COLLECTIONS} reached.`,
            "LIBRARY_WORKER_COLLECTION_LIMIT",
            "RangeError"
        );
    }
}

function touch(collection) {
    collection.updatedAt = new Date().toISOString();
    collection.version += 1;
}

async function cloneRecords(
    records,
    id = null,
    progressPhase = "copy",
    deep = false,
    progress = true
) {
    const output = new Array(records.length);
    const interval = DEFAULT_PROGRESS_INTERVAL;

    for (let index = 0; index < records.length; index += 1) {
        assertActive(id);

        output[index] = deep
            ? structuredCloneSafe(records[index])
            : records[index];

        if (
            progress &&
            index > 0 &&
            index % interval === 0
        ) {
            postProgress(
                id,
                progressPhase,
                index,
                records.length
            );
        }

        if (index > 0 && index % YIELD_INTERVAL === 0) {
            await yieldToWorker();
        }
    }

    return output;
}

function structuredCloneSafe(value) {
    if (typeof structuredClone === "function") {
        return structuredClone(value);
    }

    if (value === undefined) {
        return undefined;
    }

    return JSON.parse(JSON.stringify(value));
}

async function setCollection(payload = {}, id = null) {
    const startedAt = now();
    const name = normalizeName(
        payload.name ??
        payload.collection
    );

    const records = normalizeRecords(payload);
    ensureCollectionCapacity(name, records.length);
    ensureCollectionSlot(name);

    const copy = normalizeBoolean(payload.copy, true);
    const deep = normalizeBoolean(
        payload.deepCopy ??
        payload.deep_copy,
        false
    );

    const copied = copy
        ? await cloneRecords(
            records,
            id,
            "set",
            deep,
            normalizeBoolean(payload.progress, true)
        )
        : records;

    const existing = collections.get(name);
    const preserveCreatedAt = normalizeBoolean(
        payload.preserveCreatedAt ??
        payload.preserve_created_at,
        true
    );

    const collection = existing || createCollection(name, []);

    collection.records = copied;
    collection.metadata = {
        ...(
            normalizeBoolean(payload.replaceMetadata, false)
                ? {}
                : collection.metadata
        ),
        ...(
            payload.metadata &&
            typeof payload.metadata === "object"
                ? payload.metadata
                : {}
        )
    };

    if (
        !existing ||
        !preserveCreatedAt
    ) {
        collection.createdAt =
            payload.createdAt ??
            payload.created_at ??
            new Date().toISOString();
    }

    touch(collection);
    collections.set(name, collection);

    return {
        ...describeCollection(collection),
        elapsed_ms: now() - startedAt
    };
}

async function getCollection(payload = {}, id = null) {
    const startedAt = now();
    const collection = requireCollection(
        payload.name ??
        payload.collection
    );

    const filtered = await filterRecords(
        collection.records,
        payload,
        id
    );

    const sorted = sortRecords(
        filtered,
        payload.sort ??
        payload.orderBy ??
        payload.order_by,
        payload.order ??
        payload.direction
    );

    const limit = integer(
        payload.limit ??
        payload.perPage ??
        payload.per_page,
        DEFAULT_LIMIT,
        1,
        MAX_LIMIT
    );

    const explicitOffset =
        payload.offset !== undefined &&
        payload.offset !== null;

    const offset = integer(
        payload.offset,
        0,
        0,
        Number.MAX_SAFE_INTEGER
    );

    const page = integer(
        payload.page,
        1,
        1,
        Number.MAX_SAFE_INTEGER
    );

    const effectiveOffset = explicitOffset
        ? offset
        : (page - 1) * limit;

    const requestedAll = normalizeBoolean(
        payload.all ??
        payload.returnAll ??
        payload.return_all,
        false
    );

    const selected = requestedAll
        ? sorted
        : sorted.slice(
            effectiveOffset,
            effectiveOffset + limit
        );

    const projected = selected.map(record =>
        projectRecord(
            record,
            payload.select ??
            payload.fields ??
            payload.projection
        )
    );

    const total = filtered.length;

    const result = {
        name: collection.name,
        version: collection.version,
        total,
        matched: total,
        returned: projected.length,
        offset: requestedAll ? 0 : effectiveOffset,
        limit: requestedAll ? total : limit,
        page: requestedAll
            ? 1
            : Math.floor(effectiveOffset / limit) + 1,
        pages: requestedAll
            ? (total > 0 ? 1 : 0)
            : Math.ceil(total / limit),
        hasPrevious: !requestedAll && effectiveOffset > 0,
        hasNext:
            !requestedAll &&
            effectiveOffset + selected.length < total,
        records: projected,
        facets: buildFacets(
            normalizeKey(
                payload.facetsScope ??
                payload.facets_scope
            ) === "page"
                ? selected
                : filtered,
            payload.facets,
            payload.facetLimit ??
            payload.facet_limit
        ),
        metadata: {
            ...collection.metadata
        },
        createdAt: collection.createdAt,
        updatedAt: collection.updatedAt,
        elapsed_ms: now() - startedAt,
        workerVersion: WORKER_VERSION
    };

    if (normalizeBoolean(
        payload.includeIndexes ??
        payload.include_indexes,
        false
    )) {
        const sourceIndexes = new Map(
            collection.records.map((record, index) => [
                record,
                index
            ])
        );

        result.indexes = selected.map(record =>
            sourceIndexes.get(record) ?? -1
        );
    }

    return result;
}

async function appendCollection(
    payload = {},
    id = null,
    prepend = false
) {
    const startedAt = now();
    const name = normalizeName(
        payload.name ??
        payload.collection
    );

    const records = normalizeRecords(payload);
    ensureCollectionSlot(name);

    let collection = collections.get(name);

    if (!collection) {
        collection = createCollection(name, []);
        collections.set(name, collection);
    }

    ensureCollectionCapacity(
        name,
        collection.records.length + records.length
    );

    const copy = normalizeBoolean(payload.copy, true);
    const deep = normalizeBoolean(
        payload.deepCopy ??
        payload.deep_copy,
        false
    );

    const incoming = copy
        ? await cloneRecords(
            records,
            id,
            prepend ? "prepend" : "append",
            deep,
            normalizeBoolean(payload.progress, true)
        )
        : records;

    if (prepend) {
        collection.records.unshift(...incoming);
    } else {
        collection.records.push(...incoming);
    }

    if (
        payload.metadata &&
        typeof payload.metadata === "object"
    ) {
        collection.metadata = {
            ...collection.metadata,
            ...payload.metadata
        };
    }

    touch(collection);

    return {
        ...describeCollection(collection),
        added: incoming.length,
        position: prepend ? "start" : "end",
        elapsed_ms: now() - startedAt
    };
}

async function mergeCollection(payload = {}, id = null) {
    const startedAt = now();
    const name = normalizeName(
        payload.name ??
        payload.collection
    );

    const records = normalizeRecords(payload);
    const key = normalizeText(
        payload.key ??
        payload.idField ??
        payload.id_field ??
        "id"
    );

    ensureCollectionSlot(name);

    let collection = collections.get(name);

    if (!collection) {
        collection = createCollection(name, []);
        collections.set(name, collection);
    }

    const replace = normalizeBoolean(payload.replace, true);
    const patch = normalizeBoolean(payload.patch, !replace);
    const allowNullKeys = normalizeBoolean(
        payload.allowNullKeys ??
        payload.allow_null_keys,
        false
    );

    const positions = new Map();

    for (let index = 0; index < collection.records.length; index += 1) {
        const recordKey = canonicalKey(
            firstRecordValue(collection.records[index], key)
        );

        if (recordKey !== null) {
            positions.set(recordKey, index);
        }
    }

    let added = 0;
    let updated = 0;
    let skipped = 0;

    for (let index = 0; index < records.length; index += 1) {
        assertActive(id);

        const incoming = records[index];
        const incomingKey = canonicalKey(
            firstRecordValue(incoming, key)
        );

        if (incomingKey === null && !allowNullKeys) {
            skipped += 1;
            continue;
        }

        if (incomingKey !== null && positions.has(incomingKey)) {
            const targetIndex = positions.get(incomingKey);

            if (!replace && !patch) {
                skipped += 1;
            } else {
                collection.records[targetIndex] = patch
                    ? {
                        ...collection.records[targetIndex],
                        ...incoming
                    }
                    : incoming;

                updated += 1;
            }
        } else {
            positions.set(
                incomingKey ??
                `__null__:${collection.records.length}`,
                collection.records.length
            );

            collection.records.push(incoming);
            added += 1;
        }

        if (
            normalizeBoolean(payload.progress, true) &&
            index > 0 &&
            index % DEFAULT_PROGRESS_INTERVAL === 0
        ) {
            postProgress(
                id,
                "merge",
                index,
                records.length,
                { added, updated, skipped }
            );
        }

        if (index > 0 && index % YIELD_INTERVAL === 0) {
            await yieldToWorker();
        }
    }

    ensureCollectionCapacity(name, collection.records.length);
    touch(collection);

    return {
        ...describeCollection(collection),
        key,
        added,
        updated,
        skipped,
        elapsed_ms: now() - startedAt
    };
}

function listCollections(payload = {}) {
    const query = normalizeKey(
        payload.query ??
        payload.q
    );

    const sort = normalizeKey(
        payload.sort ??
        "name"
    );

    const order = normalizeKey(
        payload.order ??
        "asc"
    ) === "desc"
        ? -1
        : 1;

    const values = [...collections.values()]
        .filter(collection =>
            !query ||
            collection.name.toLowerCase().includes(query) ||
            safeStringify(collection.metadata)
                .toLowerCase()
                .includes(query)
        )
        .map(describeCollection);

    values.sort((left, right) => {
        if (sort === "records") {
            return (
                left.records - right.records ||
                left.name.localeCompare(right.name)
            ) * order;
        }

        if (sort === "updated" || sort === "updatedat") {
            return (
                Date.parse(left.updatedAt) -
                Date.parse(right.updatedAt)
            ) * order;
        }

        if (sort === "created" || sort === "createdat") {
            return (
                Date.parse(left.createdAt) -
                Date.parse(right.createdAt)
            ) * order;
        }

        return left.name.localeCompare(
            right.name,
            undefined,
            {
                numeric: true,
                sensitivity: "base"
            }
        ) * order;
    });

    return values;
}

function describeCollection(collection) {
    return {
        name: collection.name,
        records: collection.records.length,
        version: collection.version,
        metadata: {
            ...collection.metadata
        },
        createdAt: collection.createdAt,
        updatedAt: collection.updatedAt,
        snapshots: snapshots.get(collection.name)?.length ?? 0
    };
}

function deleteCollection(payload = {}) {
    const name = normalizeName(
        payload.name ??
        payload.collection
    );

    const existed = collections.delete(name);

    if (normalizeBoolean(
        payload.deleteSnapshots ??
        payload.delete_snapshots,
        true
    )) {
        snapshots.delete(name);
    }

    return {
        deleted: existed,
        name,
        remaining: collections.size
    };
}

function renameCollection(payload = {}) {
    const from = normalizeName(
        payload.name ??
        payload.from ??
        payload.collection
    );

    const to = normalizeName(
        payload.newName ??
        payload.new_name ??
        payload.to
    );

    if (from === to) {
        return describeCollection(
            requireCollection(from)
        );
    }

    if (
        collections.has(to) &&
        !normalizeBoolean(payload.overwrite, false)
    ) {
        throw createError(
            `Library collection already exists: ${to}`,
            "LIBRARY_WORKER_COLLECTION_EXISTS"
        );
    }

    const collection = requireCollection(from);

    if (collections.has(to)) {
        collections.delete(to);
    }

    collections.delete(from);
    collection.name = to;
    touch(collection);
    collections.set(to, collection);

    if (snapshots.has(from)) {
        const existing = snapshots.get(to) ?? [];
        snapshots.set(
            to,
            [...existing, ...snapshots.get(from)]
                .slice(-MAX_SNAPSHOTS_PER_COLLECTION)
        );
        snapshots.delete(from);
    }

    return describeCollection(collection);
}

async function cloneCollection(payload = {}, id = null) {
    const source = requireCollection(
        payload.name ??
        payload.from ??
        payload.collection
    );

    const targetName = normalizeName(
        payload.newName ??
        payload.new_name ??
        payload.to
    );

    if (
        collections.has(targetName) &&
        !normalizeBoolean(payload.overwrite, false)
    ) {
        throw createError(
            `Library collection already exists: ${targetName}`,
            "LIBRARY_WORKER_COLLECTION_EXISTS"
        );
    }

    ensureCollectionSlot(targetName);

    const deep = normalizeBoolean(
        payload.deep ??
        payload.deepCopy ??
        payload.deep_copy,
        false
    );

    const records = await cloneRecords(
        source.records,
        id,
        "clone",
        deep,
        normalizeBoolean(payload.progress, true)
    );

    const collection = createCollection(
        targetName,
        records,
        {
            ...source.metadata,
            ...(
                payload.metadata &&
                typeof payload.metadata === "object"
                    ? payload.metadata
                    : {}
            ),
            clonedFrom: source.name
        }
    );

    collections.set(targetName, collection);

    return describeCollection(collection);
}

function clearCollections(payload = {}) {
    const names = uniqueStrings(
        payload.names ??
        payload.collections
    );

    if (names.length) {
        let deleted = 0;

        for (const name of names) {
            if (collections.delete(normalizeName(name))) {
                deleted += 1;
            }

            if (normalizeBoolean(
                payload.deleteSnapshots ??
                payload.delete_snapshots,
                true
            )) {
                snapshots.delete(name);
            }
        }

        return {
            deleted,
            remaining: collections.size
        };
    }

    const count = collections.size;
    collections.clear();

    if (normalizeBoolean(
        payload.deleteSnapshots ??
        payload.delete_snapshots,
        true
    )) {
        snapshots.clear();
    }

    return {
        deleted: count,
        remaining: 0
    };
}

function countCollection(payload = {}) {
    return requireCollection(
        payload.name ??
        payload.collection
    ).records.length;
}

function collectionStats(payload = {}) {
    if (payload.name || payload.collection) {
        return calculateStats(
            requireCollection(
                payload.name ??
                payload.collection
            )
        );
    }

    const values = [...collections.values()];
    const totalRecords = values.reduce(
        (sum, collection) =>
            sum + collection.records.length,
        0
    );

    return {
        collections: values.length,
        records: totalRecords,
        largest: values.length
            ? values
                .map(describeCollection)
                .sort((left, right) =>
                    right.records - left.records ||
                    left.name.localeCompare(right.name)
                )[0]
            : null,
        smallest: values.length
            ? values
                .map(describeCollection)
                .sort((left, right) =>
                    left.records - right.records ||
                    left.name.localeCompare(right.name)
                )[0]
            : null,
        averageRecords:
            values.length
                ? totalRecords / values.length
                : 0,
        snapshots: [...snapshots.values()]
            .reduce(
                (sum, entries) =>
                    sum + entries.length,
                0
            ),
        updatedAt: values.length
            ? values
                .map(collection => collection.updatedAt)
                .sort()
                .at(-1)
            : null
    };
}

function calculateStats(collection) {
    const fields = new Set();
    const fieldCounts = new Map();

    let nullValues = 0;
    let scalarValues = 0;
    let objectValues = 0;
    let arrayValues = 0;

    for (const record of collection.records) {
        collectStats(
            record,
            "",
            fields,
            fieldCounts,
            {
                incrementNull: () => {
                    nullValues += 1;
                },
                incrementScalar: () => {
                    scalarValues += 1;
                },
                incrementObject: () => {
                    objectValues += 1;
                },
                incrementArray: () => {
                    arrayValues += 1;
                }
            }
        );
    }

    return {
        ...describeCollection(collection),
        fields: [...fields].sort(),
        fieldCount: fields.size,
        fieldPresence: [...fieldCounts.entries()]
            .sort((left, right) =>
                right[1] - left[1] ||
                left[0].localeCompare(right[0])
            )
            .map(([field, count]) => ({
                field,
                count,
                percent:
                    collection.records.length
                        ? (count / collection.records.length) * 100
                        : 0
            })),
        values: {
            null: nullValues,
            scalar: scalarValues,
            object: objectValues,
            array: arrayValues
        }
    };
}

function collectStats(
    value,
    prefix,
    fields,
    fieldCounts,
    counters,
    seenInRecord = null
) {
    const seen = seenInRecord ?? new Set();

    if (value === null || value === undefined) {
        counters.incrementNull();
        return;
    }

    if (Array.isArray(value)) {
        counters.incrementArray();

        for (const item of value) {
            collectStats(
                item,
                prefix,
                fields,
                fieldCounts,
                counters,
                seen
            );
        }

        return;
    }

    if (typeof value !== "object") {
        counters.incrementScalar();
        return;
    }

    counters.incrementObject();

    for (const [key, child] of Object.entries(value)) {
        const path = prefix
            ? `${prefix}.${key}`
            : key;

        fields.add(path);

        if (!seen.has(path)) {
            seen.add(path);
            fieldCounts.set(
                path,
                (fieldCounts.get(path) || 0) + 1
            );
        }

        collectStats(
            child,
            path,
            fields,
            fieldCounts,
            counters,
            seen
        );
    }
}

async function deduplicateCollection(payload = {}, id = null) {
    const startedAt = now();
    const collection = requireCollection(
        payload.name ??
        payload.collection
    );

    const key = normalizeText(
        payload.key ??
        payload.idField ??
        payload.id_field ??
        "id"
    );

    const keep = normalizeKey(payload.keep ?? "first");
    const records = [];
    const indexByKey = new Map();
    let removed = 0;

    for (
        let index = 0;
        index < collection.records.length;
        index += 1
    ) {
        assertActive(id);

        const record = collection.records[index];
        const value = canonicalKey(
            firstRecordValue(record, key)
        );

        if (value === null) {
            records.push(record);
            continue;
        }

        if (!indexByKey.has(value)) {
            indexByKey.set(value, records.length);
            records.push(record);
        } else if (keep === "last") {
            records[indexByKey.get(value)] = record;
            removed += 1;
        } else {
            removed += 1;
        }

        if (
            normalizeBoolean(payload.progress, true) &&
            index > 0 &&
            index % DEFAULT_PROGRESS_INTERVAL === 0
        ) {
            postProgress(
                id,
                "dedupe",
                index,
                collection.records.length,
                { removed }
            );
        }

        if (index > 0 && index % YIELD_INTERVAL === 0) {
            await yieldToWorker();
        }
    }

    collection.records = records;
    touch(collection);

    return {
        ...describeCollection(collection),
        removed,
        key,
        keep,
        elapsed_ms: now() - startedAt
    };
}

